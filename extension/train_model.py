"""Train the TinyML risk model and export it for the Arduino.

Reads labelled sessions from data/ (real, from log_serial.py) and synthetic/ (from
make_synthetic.py), trains a tiny neural network, tests it on real sessions it never
saw, and writes ../stabiliknee/model.h for the firmware.

Usage:
    python train_model.py
"""
import csv
import glob
import random

from sklearn.neural_network import MLPClassifier

RISK_ON = 80.0          # basic threshold, for comparison
RISKY_MIN_MAG = 25.0    # in a risky session, only the moving part counts as risky
HIDDEN = 6              # small enough for the Uno's 2 KB of RAM
MODEL_H = "../stabiliknee/model.h"


def load_session(path):
    with open(path) as f:
        rows = list(csv.DictReader(f))
    mags = [float(r["mag_raw"]) for r in rows]
    flex = [float(r.get("flex", 0)) / 1023 for r in rows]
    label = int(rows[0]["label"])
    X, y, prev = [], [], mags[0] if mags else 0.0
    for m, fl in zip(mags, flex):
        jerk = (m - prev) / 0.02  # same 20 ms step as the firmware
        prev = m
        X.append([m, jerk, fl])
        y.append(1 if label == 1 and m > RISKY_MIN_MAG else 0)
    return X, y, label, mags


def scale(X, mean, std):
    return [[(v - mu) / sd for v, mu, sd in zip(row, mean, std)] for row in X]


def onsets(flags):
    return sum(1 for a, b in zip([False] + flags, flags) if b and not a)


def main():
    real = sorted(glob.glob("data/*.csv"))
    synthetic = sorted(glob.glob("synthetic/*.csv"))
    if not real and not synthetic:
        raise SystemExit("No data. Run log_serial.py and/or make_synthetic.py first.")

    random.seed(42)
    random.shuffle(real)
    n_test = max(1, len(real) * 3 // 10) if len(real) >= 2 else 0
    test_files, train_files = real[:n_test], real[n_test:] + synthetic
    if not test_files:
        print("WARNING: fewer than 2 real sessions, so the test uses synthetic data only.")
        random.shuffle(synthetic)
        cut = max(1, len(synthetic) * 3 // 10)
        test_files, train_files = synthetic[:cut], synthetic[cut:]

    X, y = [], []
    for path in train_files:
        Xs, ys, _, _ = load_session(path)
        X += Xs
        y += ys
    if len(set(y)) < 2:
        raise SystemExit("Training data needs both normal (label 0) and risky (label 1) sessions.")

    cols = list(zip(*X))
    mean = [sum(c) / len(c) for c in cols]
    std = [max((sum((v - mu) ** 2 for v in c) / len(c)) ** 0.5, 1e-6) for c, mu in zip(cols, mean)]

    model = MLPClassifier(hidden_layer_sizes=(HIDDEN,), activation="relu", max_iter=2000, random_state=0)
    model.fit(scale(X, mean, std), y)

    # Test on sessions the model never saw
    stats = {"model": [0, 0], "basic": [0, 0]}  # [false alarms, risky sessions caught]
    normal_min, risky = 0.0, 0
    for path in test_files:
        Xs, _, label, mags = load_session(path)
        preds = {"model": [bool(p) for p in model.predict(scale(Xs, mean, std))],
                 "basic": [m > RISK_ON for m in mags]}
        if label == 0:
            normal_min += len(Xs) * 0.02 / 60
        else:
            risky += 1
        for name, flags in preds.items():
            if label == 0:
                stats[name][0] += onsets(flags)
            elif any(flags):
                stats[name][1] += 1

    print(f"Trained on {len(X)} readings from {len(train_files)} sessions "
          f"({len(synthetic)} synthetic available)")
    print(f"Tested on {len(test_files)} unseen sessions: {normal_min:.1f} min normal, {risky} risky\n")
    for name, (fa, caught) in stats.items():
        rate = fa / normal_min if normal_min else float("nan")
        det = 100 * caught / risky if risky else float("nan")
        print(f"{name:6} false alarms/min: {rate:5.2f} | risky caught: {det:5.1f}%")
    if stats["basic"][0]:
        cut = 100 * (stats["basic"][0] - stats["model"][0]) / stats["basic"][0]
        print(f"\nModel cut false alarms by {cut:.0f}% vs the basic threshold")

    export(model, mean, std)
    print(f"\nWrote {MODEL_H}. Re-upload stabiliknee.ino to run the model on the brace.")


def export(model, mean, std):
    def arr(values):
        return ", ".join(f"{v:.6f}f" for v in values)

    w1 = [w for row in model.coefs_[0] for w in row]  # 3 inputs x HIDDEN, row-major
    w2 = [row[0] for row in model.coefs_[1]]
    with open(MODEL_H, "w") as f:
        f.write("// Generated by extension/train_model.py. Do not edit by hand.\n")
        f.write("#define MODEL_READY 1\n")
        f.write(f"const int HIDDEN = {HIDDEN};\n")
        f.write(f"const float FEAT_MEAN[3] = {{{arr(mean)}}};\n")
        f.write(f"const float FEAT_STD[3] = {{{arr(std)}}};\n")
        f.write(f"const float W1[3 * {HIDDEN}] = {{{arr(w1)}}};\n")
        f.write(f"const float B1[{HIDDEN}] = {{{arr(model.intercepts_[0])}}};\n")
        f.write(f"const float W2[{HIDDEN}] = {{{arr(w2)}}};\n")
        f.write(f"const float B2 = {model.intercepts_[1][0]:.6f}f;\n")


if __name__ == "__main__":
    main()
